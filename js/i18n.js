  /* ───── Tradução ───── */
  const warned = new Set();
  function missing(key) {
    if (!warned.has(key)) {
      warned.add(key);
      IP.i18nMissing.push(key);
      console.warn('[i18n] missing key "' + key + '" (' + IP.lang + ')');
    }
    return '\u27e6' + key + '\u27e7';
  }
  function pick(lang, key, vars) {
    const d = IP.dict[lang];
    if (vars && vars.count != null) {
      const form = vars.count === 1 ? '.one' : '.other';
      if (d[key + form] != null) return d[key + form];
    }
    return d[key] != null ? d[key] : null;
  }

  /** Texto traduzido. vars: { nome: valor } troca {nome}; vars.count escolhe key.one (count = 1) ou key.other
      e sai formatado em {count}. Chave ausente: aviso no console e marcador ⟦chave⟧. */
  IP.t = function (key, vars) {
    if (vars && 'count' in vars && vars.count == null) vars = Object.assign({}, vars, { count: 0 });
    let s = pick(IP.lang, key, vars);
    if (s == null) {
      s = pick(IP.lang === 'pt' ? 'en' : 'pt', key, vars);
      if (s == null) return missing(key);
      missing(key);
    }
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, name) => {
      if (!(name in vars)) return m;
      const v = vars[name];
      return name === 'count' && typeof v === 'number' ? IP.fmt.int(v) : String(v);
    });
  };

  /* ───── Texto estático: data-i18n, data-i18n-html, data-i18n-attr="atributo:chave,..." ───── */
  IP.applyStatic = function (scope) {
    const rootNode = scope || document;
    rootNode.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = IP.t(n.getAttribute('data-i18n')); });
    rootNode.querySelectorAll('[data-i18n-html]').forEach((n) => { n.innerHTML = IP.t(n.getAttribute('data-i18n-html')); });
    rootNode.querySelectorAll('[data-i18n-attr]').forEach((n) => {
      n.getAttribute('data-i18n-attr').split(',').forEach((pair) => {
        const i = pair.indexOf(':');
        if (i > 0) n.setAttribute(pair.slice(0, i).trim(), IP.t(pair.slice(i + 1).trim()));
      });
    });
  };

  /* ───── Troca de idioma: grava, tira ?lang= da URL, guarda a rolagem e recarrega ───── */
  IP.setLang = function (lang) {
    if (!LANGS.includes(lang) || lang === IP.lang) return;
    let saved = true;
    try { localStorage.setItem(KEY, lang); } catch (e) { saved = false; /* modo privado: a escolha vai na URL */ }
    try { sessionStorage.setItem(SCROLL_KEY, String(Math.round(window.scrollY))); } catch (e) { /* modo privado */ }
    const url = new URL(location.href);
    if (saved) url.searchParams.delete('lang'); else url.searchParams.set('lang', lang);
    location.replace(url.pathname + url.search + url.hash);
  };

  /* Devolve a rolagem de antes da troca; chamado por main.js depois de montar a página. */
  IP.restoreScroll = function () {
    let y = null;
    try { y = sessionStorage.getItem(SCROLL_KEY); sessionStorage.removeItem(SCROLL_KEY); } catch (e) { /* modo privado */ }
    if (y != null && Number.isFinite(Number(y))) window.scrollTo({ top: Number(y), behavior: 'instant' });
    if ('scrollRestoration' in history) history.scrollRestoration = 'auto';
  };
  try {
    if (sessionStorage.getItem(SCROLL_KEY) != null && 'scrollRestoration' in history) history.scrollRestoration = 'manual';
  } catch (e) { /* modo privado */ }

  function init() {
    IP.applyStatic(document);
    const btn = document.getElementById('lang-toggle');
    if (btn) {
      btn.setAttribute('aria-pressed', String(IP.lang === 'en'));
      btn.addEventListener('click', () => IP.setLang(IP.lang === 'en' ? 'pt' : 'en'));
    }
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();

